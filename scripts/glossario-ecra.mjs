// TEMPORÁRIO: acrescenta palavras ao Glossário, recarrega e confirma que ficaram; captura em base64 aos bocados
import { chromium } from "playwright";
const b = await chromium.launch();
const p = await b.newPage({ viewport: { width: 1280, height: 1000 } });
const erros = [];
p.on("pageerror", (e) => erros.push(`pageerror: ${e.message}`));
p.on("console", (m) => { if (m.type() === "error" && !/Failed to load resource/.test(m.text())) erros.push(`console: ${m.text()}`); });
const abrir = async () => {
  await p.goto("http://localhost:3001/", { waitUntil: "domcontentloaded" });
  await p.getByRole("button", { name: /^Glossário/ }).click();
  await p.waitForSelector(".glos", { timeout: 20000 });
};
await abrir();
await p.getByRole("button", { name: "+ Acrescentar ao glossário" }).click();
await p.getByLabel("Expressão").fill("chocolate");
await p.getByLabel("Definição").fill("Remate fraco, sem força");
await p.getByLabel("Sinónimos").fill("remate mole, passe ao guarda-redes");
await p.getByRole("button", { name: "Guardar" }).click();
console.log("== depois de guardar ==", await p.locator(".gfeito").first().innerText());
await p.getByLabel("Categoria").selectOption("clube");
await p.getByLabel("Clube").fill("Milan");
await p.getByLabel("Alcunhas").fill("Os do Diabo");
await p.getByRole("button", { name: "Guardar" }).click();
await abrir(); // recarregar: tem de continuar lá
console.log("== botão ==", await p.locator(".gmeus .textbtn").first().innerText());
await p.locator(".gmods").getByRole("button", { name: "Todas" }).click();
await p.locator(".gform input").first().fill("chocolate");
await p.getByRole("button", { name: "Procurar" }).click();
await p.waitForSelector(".gres");
console.log("== pesquisa chocolate ==", (await p.locator(".gres").innerText()).replace(/\s+/g, " ").slice(0, 200));
console.log("== chips meus em Expressões ==", await p.locator(".gchip.meu").count());
await p.getByRole("button", { name: /^As minhas palavras/ }).click();
console.log("== as minhas palavras ==", (await p.locator(".gmeus-lista").innerText()).replace(/\s+/g, " "));
await p.locator(".gabas").getByRole("button", { name: "Clubes" }).click();
await p.locator(".gmods").getByRole("button", { name: /Itália/ }).click();
console.log("== Milan ==", (await p.locator(".gclube", { hasText: "Milan" }).first().innerText()).replace(/\s+/g, " "));
await p.getByRole("button", { name: "+ Acrescentar ao glossário" }).click();
await p.evaluate(() => window.scrollTo(0, 230));
const img = (await p.screenshot({ type: "jpeg", quality: 45 })).toString("base64");
console.log("== erros ==", erros.length ? erros.join("\n") : "nenhum");
for (let i = 0; i < img.length; i += 4000) console.log(`IMG${String(i / 4000).padStart(3, "0")} ${img.slice(i, i + 4000)}`);
await b.close();
